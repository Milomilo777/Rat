use rat_types::Protocol;

/// The service usually found on a well-known port
pub fn service_name(port: u16, proto: Protocol) -> Option<&'static str> {
    if proto == Protocol::Udp {
        if let Some(n) = udp_name(port) {
            return Some(n);
        }
    }
    if proto == Protocol::Tcp {
        if let Some(n) = tcp_name(port) {
            return Some(n);
        }
    }
    common_name(port)
}

fn udp_name(port: u16) -> Option<&'static str> {
    match port {
        443 => Some("QUIC"),
        853 => Some("DoQ"),
        4500 => Some("IPSec-NAT"),
        _ => None,
    }
}

fn tcp_name(_port: u16) -> Option<&'static str> {
    None
}

